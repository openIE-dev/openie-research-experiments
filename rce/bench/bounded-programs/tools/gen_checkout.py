"""Write an RCE checkout with N independent options as one record-typed state.

Options cycle through four shapes, each with its own events and one error:
  flag   (gift wrap, insurance, ...): a bool toggled by an event; adds a fee
  region (tax region of a line):      a u8 0..3 set by an event, refined
  hold   (inventory hold on a line):  a u8 count 0..3, Hold/Release keep at the ends
  promo  (promo code):                a bool set once; a second Apply keeps the state
Place emits the total, a sum of one term per option, so the work of a step
is linear in N.
"""
import sys

SHAPES = ["flag", "region", "hold", "promo"]

def gen(n):
    L = []
    L.append(f"# A checkout with {n} independent options in one record-typed state.")
    L.append("# Generated by gen_checkout.py; each option has its own events.")
    L.append(f'intent "a checkout of {n} independent options: the program grows by one field and its steps per option"')
    L.append("    example Toggle0, Toggle0, Toggle0 -> flag0")
    L.append("    example Hold2, Hold2, Hold2, Hold2 -> kept: AtLimit" if n > 2 else "    example Toggle0 -> flag0")
    L.append("    example Apply3, Apply3 -> kept: AlreadyApplied" if n > 3 else "    example Toggle0 -> flag0")
    L.append("")
    L.append("type Region = u8 where self <= 3")
    L.append("")
    L.append("state Checkout")
    for i in range(n):
        s = SHAPES[i % 4]
        if s == "flag": L.append(f"    flag{i}: bool = false")
        elif s == "region": L.append(f"    region{i}: Region = 0")
        elif s == "hold": L.append(f"    hold{i}: u8 = 0")
        else: L.append(f"    promo{i}: bool = false")
    L.append("")
    L.append("struct Total")
    L.append("    cents: i64")
    L.append("")
    L.append("error AtLimit")
    L.append("error AlreadyApplied")
    L.append("")
    for i in range(n):
        s = SHAPES[i % 4]
        if s == "flag": L.append(f"event Toggle{i}")
        elif s == "region": L.append(f"event SetRegion{i}(r: Region)")
        elif s == "hold": L += [f"event Hold{i}", f"event Release{i}"]
        else: L.append(f"event Apply{i}")
    L.append("event Place")
    L.append("")
    for i in range(n):
        s = SHAPES[i % 4]
        if s == "flag":
            L += [f"step Checkout on Toggle{i}", f"    flag{i} = not flag{i}"]
        elif s == "region":
            L += [f"step Checkout on SetRegion{i}(r: r)", f"    region{i} = r"]
        elif s == "hold":
            L += [f"step Checkout on Hold{i} if hold{i} == 3", "    fail AtLimit",
                  f"step Checkout on Hold{i}", f"    hold{i} += 1",
                  f"step Checkout on Release{i} if hold{i} == 0", "    fail AtLimit",
                  f"step Checkout on Release{i}", f"    hold{i} -= 1"]
        else:
            L += [f"step Checkout on Apply{i} if promo{i}", "    fail AlreadyApplied",
                  f"step Checkout on Apply{i}", f"    promo{i} = true"]
    L.append("step Checkout on Place")
    L.append("    var t: i64 = 1000")
    for i in range(n):
        s = SHAPES[i % 4]
        if s == "flag": L.append(f"    t += if flag{i} then {100 + i} else 0")
        elif s == "region": L.append(f"    t += (region{i} as i64) * {7 + i}")
        elif s == "hold": L.append(f"    t += (hold{i} as i64) * 250")
        else: L.append(f"    t -= if promo{i} then {50 + i} else 0")
    L.append("    emit Total(cents: t)")
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    sys.stdout.write(gen(int(sys.argv[1])))
