def _unescape_gnu_sha256_path(raw_path: str) -> str:
    """Decode GNU coreutils sha256sum backslash-escaped file paths (`\\\\`, `\\\"`, `\\n`)."""
    out: list[str] = []
    i = 0
    n = len(raw_path)
    while i < n:
        ch = raw_path[i]
        if ch == "\\" and i + 1 < n:
            nxt = raw_path[i + 1]
            if nxt == "\\":
                out.append("\\")
                i += 2
                continue
            if nxt == "n":
                out.append("\n")
                i += 2
                continue
            if nxt == '"':
                out.append('"')
                i += 2
                continue
        out.append(ch)
        i += 1
    return "".join(out)


def audit_repository_checksums(repo_root: Path) -> dict[str, Any]:
    """Verify `CHECKSUMS.sha256` at repository root and report exact matched / total counts."""
    chk_path = repo_root / "CHECKSUMS.sha256"
    if not chk_path.is_file():
        return {
            "checksums_file_present": False,
            "total_entries": 0,
            "matched_entries": 0,
            "missing_files": [],
            "mismatched_files": [],
        }

    total = 0
    matched = 0
    missing: list[str] = []
    mismatched: list[str] = []

    for raw_line in chk_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        escaped = False
        if line.startswith("\\"):
            escaped = True
            line = line[1:]
        if "  " in line:
            expected_hex, rel_str = line.split("  ", 1)
        elif " *" in line:
            expected_hex, rel_str = line.split(" *", 1)
        else:
            parts = line.split(None, 1)
            if len(parts) != 2:
                continue
            expected_hex, rel_str = parts
        if escaped:
            rel_str = _unescape_gnu_sha256_path(rel_str)

        total += 1
        target = repo_root / rel_str
        if not target.is_file():
            missing.append(rel_str)
            continue
        actual_hex = hashlib.sha256(target.read_bytes()).hexdigest()
        if actual_hex == expected_hex.lower():
            matched += 1
        else:
            mismatched.append(rel_str)

    return {
        "checksums_file_present": True,
        "total_entries": total,
        "matched_entries": matched,
        "missing_count": len(missing),
        "mismatched_count": len(mismatched),
        "missing_files_sample": missing[:10],
        "mismatched_files_sample": mismatched[:10],
        "all_matched": (total > 0 and matched == total),
    }


