def main() -> int:
    parser = argparse.ArgumentParser(description="OpenIE Standalone External Replication Harness")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--out", type=Path, default=None, help="Output directory (default: replicate/out)")
    parser.add_argument("--quick", action="store_true", help="Run reduced iteration counts for fast CI smoke checks")
    parser.add_argument("--skip-native", action="store_true", help="Skip optional C/Rust native micro-kernels")
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    out_dir = args.out if args.out is not None else (repo_root / "replicate" / "out")
    if not out_dir.is_absolute():
        out_dir = (Path.cwd() / out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    t_start = time.perf_counter()
    meter = EnergyMeter()
    idle_pre = meter.sample_idle_power(0.15) if meter.available else None
    host_info = collect_sanitized_host_info(skip_native=args.skip_native)

    print(f"[1/4] Auditing repository CHECKSUMS.sha256 in {repo_root.name} ...")
    chk_audit = audit_repository_checksums(repo_root)
    print(
        f"      CHECKSUMS.sha256: {chk_audit['matched_entries']} / {chk_audit['total_entries']} matched "
        f"(missing={chk_audit['missing_count']}, mismatched={chk_audit['mismatched_count']})"
    )

    print("[2/4] Running Suite 1: deterministic-null (content-addressed control & replay bound) ...")
    s1 = run_suite_deterministic_null(repo_root, meter, quick=args.quick, skip_native=args.skip_native)
    print(
        f"      Suite 1 done: 0/{s1['total_episodes']} replay divergences; "
        f"Python {s1['timing_and_serialization_comparison']['dnull_lookup_plus_solver_ns_per_query']['median']} ns/q "
        f"vs {s1['timing_and_serialization_comparison']['prompt_serialize_tokenize_ns_per_query']['median']} ns/q prompt floor"
    )

    print("[3/4] Running Suite 2: rce-compile (De Bruijn 1972 soundness & compile payback N*) ...")
    s2 = run_suite_rce_compile(repo_root, meter, quick=args.quick, skip_native=args.skip_native)
    print(
        f"      Suite 2 done: De Bruijn {s2['debruijn_canonicalization']['debruijn_alpha_hits']}/120 alpha hits, "
        f"{s2['debruijn_canonicalization']['debruijn_false_positive_collisions_total']}/200 mutant collisions; "
        f"AST N*={s2['python_static_admission_amortization']['n_star_invocations']['median']}"
    )

    print("[4/4] Running Suite 3: ai-reads-human (N=50 UTF-8 JSON vs 23-byte binary parsing) ...")
    s3 = run_suite_ai_reads_human(repo_root, meter, quick=args.quick, skip_native=args.skip_native)
    print(
        f"      Suite 3 done: bytes {s3['payload_bytes']['byte_ratio_json_compact_vs_binary']}x, "
        f"Python parse {s3['python_stdlib_parse']['wall_time_ratio_json_compact_vs_binary']}x "
        f"(evidence_class={meter.evidence_class})"
    )

    idle_post = meter.sample_idle_power(0.15) if meter.available else None
    energy_meta = meter.metadata()
    if idle_pre is not None and idle_post is not None:
        mean_idle = 0.5 * (idle_pre + idle_post)
        drift_pct = round(100.0 * abs(idle_post - idle_pre) / mean_idle, 2) if mean_idle > 0 else 0.0
        energy_meta["idle_pkg_w_pre"] = idle_pre
        energy_meta["idle_pkg_w_post"] = idle_post
        energy_meta["idle_drift_pct"] = drift_pct

    report: dict[str, Any] = {
        "schema": "openie.external_replication_report.v1",
        "harness_role": "Independent Replication Harness comparing local execution against OpenIE Self-Checked Reference Artifacts",
        "license": "Apache-2.0",
        "recorded_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "mode": "quick" if args.quick else "standard",
        "total_wall_seconds": round(time.perf_counter() - t_start, 3),
        "host": host_info,
        "energy_telemetry": energy_meta,
        "repository_integrity_audit": chk_audit,
        "suites": {
            "deterministic_null": s1,
            "rce_compile": s2,
            "ai_reads_human": s3,
        },
    }

    json_str = json.dumps(report, indent=2, sort_keys=False) + "\n"
    md_str = render_markdown_report(report)

    # Enforce strict privacy & path sanitization before writing any bytes to disk
    assert_sanitized(json_str)
    assert_sanitized(md_str)

    json_out = out_dir / "replication-report.json"
    md_out = out_dir / "replication-report.md"
